// --- Music Sidebar Toggle Logic ---
let isMusicSidebarOpen = false;

function toggleMusicSidebar() {
    const sidebar = document.getElementById('right-sidebar');
    const collapsedContent = document.getElementById('music-sidebar-collapsed');
    const expandedContent = document.getElementById('music-widget-container');

    if (!sidebar || !collapsedContent || !expandedContent) return;

    // Toggle State
    isMusicSidebarOpen = !isMusicSidebarOpen;

    if (isMusicSidebarOpen) {
        // OPEN SIDEBAR
        sidebar.classList.remove('xl:w-20');
        sidebar.classList.add('xl:w-[400px]');

        // Hide Button First, Then Show Widget
        collapsedContent.classList.add('opacity-0');

        setTimeout(() => {
            collapsedContent.classList.add('hidden', 'xl:hidden');
            collapsedContent.classList.remove('xl:flex');

            expandedContent.classList.remove('hidden', 'xl:hidden');
            expandedContent.classList.add('xl:flex'); // Ensure flex is applied for desktop

            // Trigger Fade In for Widget
            // Use requestAnimationFrame or small timeout to ensure display:flex is applied before opacity transition
            requestAnimationFrame(() => {
                expandedContent.classList.remove('opacity-0');
            });
        }, 200); // 200ms delay to sync with width transition start

    } else {
        // CLOSE SIDEBAR
        sidebar.classList.remove('xl:w-[400px]');
        sidebar.classList.add('xl:w-20');

        // Hide Widget First, Then Show Button
        expandedContent.classList.add('opacity-0');

        setTimeout(() => {
            expandedContent.classList.add('hidden', 'xl:hidden');
            expandedContent.classList.remove('xl:flex');

            collapsedContent.classList.remove('hidden', 'xl:hidden');
            collapsedContent.classList.add('xl:flex');

            // Trigger Fade In for Button
            requestAnimationFrame(() => {
                collapsedContent.classList.remove('opacity-0');
            });
        }, 200);
    }
}

