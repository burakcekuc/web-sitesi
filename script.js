    // Initialize Theme
    const preferredTheme = localStorage.getItem('theme');
    const systemDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    let isDark = preferredTheme === 'dark' || (!preferredTheme && systemDark);

