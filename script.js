// --- MUSIC WIDGET LOGIC ---
let lastMusicData = null;

async function fetchMusicData() {
    if (!document.getElementById('music-widget-container')) return;

    try {
        const response = await fetch(`https://ws.audioscrobbler.com/2.0/?method=user.getrecenttracks&user=${LASTFM_USERNAME}&api_key=${LASTFM_API_KEY}&format=json&limit=10`);
        const data = await response.json();

        if (data.recenttracks && data.recenttracks.track) {
            lastMusicData = data.recenttracks.track;
            renderMusicWidget(lastMusicData);
        }
    } catch (error) {
        console.error("Error fetching music data:", error);
    }
}

function renderMusicWidget(tracks) {
    const nowPlayingCard = document.getElementById('now-playing-card');
    const historyList = document.getElementById('history-list');

    // UI Elements
    const headerText = document.getElementById('music-header-text');
    const statusDot = document.getElementById('music-status-dot');
    const npArt = document.getElementById('np-art');
    const npTitle = document.getElementById('np-title');
    const npArtist = document.getElementById('np-artist');
    const npAlbum = document.getElementById('np-album');
    const equalizer = document.querySelector('.equalizer');

    if (!tracks || tracks.length === 0) return;

    // 1. Handle Status Logic
    const currentTrack = tracks[0];
    const isPlaying = currentTrack['@attr'] && currentTrack['@attr'].nowplaying === "true";

    // Update Header Status
    if (isPlaying) {
        if (headerText) {
            headerText.setAttribute('data-i18n', 'music_listening_now');
            headerText.textContent = translations[currentLang].music_listening_now;
        }

        // Green Pulse
        if (statusDot) {
            statusDot.innerHTML = `
                <span class="animate-ping absolute inline-flex h-full w-full rounded-full bg-green-400 opacity-75"></span>
                <span class="relative inline-flex rounded-full h-2 w-2 bg-green-500"></span>
            `;
        }
    } else {
        if (headerText) {
            headerText.setAttribute('data-i18n', 'music_status_idle');
            headerText.textContent = translations[currentLang].music_status_idle;
        }

        // Gray Static Dot
        if (statusDot) {
            statusDot.innerHTML = `
                <span class="relative inline-flex rounded-full h-2 w-2 bg-slate-300 dark:bg-zinc-600"></span>
            `;
        }
    }

    // Update Card Content
    if (isPlaying) {
        // --- PLAYING STATE ---
        const artUrl = currentTrack.image[2]['#text'];
        if (artUrl) {
            npArt.src = artUrl;
            npArt.style.opacity = '1';
        } else {
            npArt.style.opacity = '0';
        }

        npTitle.textContent = currentTrack.name;
        npArtist.textContent = currentTrack.artist['#text'];
        npAlbum.textContent = currentTrack.album['#text'];

        // Show Equalizer
        if (equalizer) equalizer.style.display = 'flex';
        nowPlayingCard.classList.add('ring-2', 'ring-primary/50');

        // Restore Image and Album Text visibility
        npArt.style.display = 'block';
        if (npAlbum && npAlbum.parentElement) npAlbum.parentElement.style.display = 'flex';

    } else {
        // --- IDLE STATE ---
        // Hide img tag
        npArt.style.display = 'none';

        npTitle.textContent = translations[currentLang].music_idle_title;
        npArtist.innerHTML = `<span class="italic opacity-70">${translations[currentLang].music_idle_desc}</span>`;

        // Hide Album info container if possible (it's flex container in HTML, might need safer way)
        if (npAlbum && npAlbum.parentElement) npAlbum.parentElement.style.display = 'none';

        // Hide Equalizer
        if (equalizer) equalizer.style.display = 'none';
        nowPlayingCard.classList.remove('ring-2', 'ring-primary/50');
    }

    // 2. Handle History List
    // Filter out the currently playing track if it exists, otherwise use all
    const historyTracks = isPlaying ? tracks.slice(1) : tracks;

    // Group by Date
    const groupedHistory = groupTracksByDate(historyTracks);

    historyList.innerHTML = ''; // Clear current

    Object.keys(groupedHistory).forEach(dateKey => {
        // Create Date Header
        const dateHeader = document.createElement('div');
        dateHeader.className = "sticky top-0 bg-surface-light/95 dark:bg-surface-dark/95 backdrop-blur-sm z-10 py-2 border-b border-border-light dark:border-zinc-700 mb-2";
        dateHeader.innerHTML = `<span class="text-[10px] font-bold text-secondary uppercase tracking-wider pl-1">${getDateLabel(dateKey)}</span>`;
        historyList.appendChild(dateHeader);

        // Create Track Items
        groupedHistory[dateKey].forEach(track => {
            const trackEl = document.createElement('div');
            trackEl.className = "flex items-center gap-3 p-2 rounded-xl hover:bg-slate-100 dark:hover:bg-zinc-800 transition-colors group/item";

            const artUrl = track.image[1]['#text']; // Medium size
            const timeAgo = getTimeAgo(track.date ? track.date.uts : Date.now() / 1000);

            trackEl.innerHTML = `
                <div class="relative w-10 h-10 rounded-lg overflow-hidden bg-slate-200 dark:bg-zinc-900 flex-shrink-0 border border-border-light dark:border-zinc-700/50">
                    ${artUrl ? `<img src="${artUrl}" class="w-full h-full object-cover">` : '<i class="fa-solid fa-music text-slate-400 absolute inset-0 m-auto text-xs"></i>'}
                </div>
                <div class="flex-1 min-w-0">
                    <h5 class="text-sm font-semibold text-text-main dark:text-white truncate group-hover/item:text-primary transition-colors">${track.name}</h5>
                    <p class="text-xs text-text-sub dark:text-gray-400 truncate">${track.artist['#text']}</p>
                </div>
                <span class="text-[10px] text-secondary whitespace-nowrap">${timeAgo}</span>
            `;
            historyList.appendChild(trackEl);
        });
    });
}

function groupTracksByDate(tracks) {
    const groups = {};
    tracks.forEach(track => {
        if (!track.date) return; // Skip if no date (shouldn't happen for history)

        // Convert Unix timestamp to JS Date string (YYYY-MM-DD)
        const date = new Date(track.date.uts * 1000);
        const dateKey = date.toISOString().split('T')[0];

        if (!groups[dateKey]) {
            groups[dateKey] = [];
        }
        groups[dateKey].push(track);
    });
    return groups;
}

function getDateLabel(dateKey) {
    const today = new Date().toISOString().split('T')[0];
    const yesterday = new Date(Date.now() - 86400000).toISOString().split('T')[0];

    if (dateKey === today) {
        return translations[currentLang].date_today || 'Bugün';
    } else if (dateKey === yesterday) {
        return translations[currentLang].date_yesterday || 'Dün';
    } else {
        // Return formatted date (e.g., 12 Feb)
        const date = new Date(dateKey);
        return date.toLocaleDateString(currentLang, { month: 'short', day: 'numeric' });
    }
}

function getTimeAgo(uts) {
    const now = Math.floor(Date.now() / 1000);
    const diff = now - uts;

    if (diff < 60) return translations[currentLang].time_just_now || 'Şimdi';

    const min = Math.floor(diff / 60);
    if (min < 60) return `${min}${translations[currentLang].time_min_ago || 'd'}`;

    const hour = Math.floor(min / 60);
    if (hour < 24) return `${hour}${translations[currentLang].time_hour_ago || 's'}`;

    return new Date(uts * 1000).toLocaleTimeString(currentLang, { hour: '2-digit', minute: '2-digit' });
}

